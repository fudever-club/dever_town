class I18nManager {
  constructor() {
    this.currentLang = 'vi';
    this.listeners = [];
    this.loadLanguage();
  }

  loadLanguage() {
    if (typeof window === 'undefined' || typeof localStorage === 'undefined') return;
    try {
      const saved = localStorage.getItem('dever_lang');
      if (saved === 'en' || saved === 'vi') {
        this.currentLang = saved;
      }
    } catch (e) {
      console.warn('Lỗi nạp ngôn ngữ:', e);
    }
  }

  setLanguage(lang) {
    if (lang !== 'vi' && lang !== 'en') return;
    this.currentLang = lang;
    if (typeof window !== 'undefined' && typeof localStorage !== 'undefined') {
      try {
        localStorage.setItem('dever_lang', lang);
      } catch (e) {}
    }

    this.applyToDOM();
    this.listeners.forEach(fn => fn(lang));
  }

  get(key) {
    const keys = key.split('.');
    let obj = TRANSLATIONS[this.currentLang];
    for (const k of keys) {
      if (obj && obj[k] !== undefined) {
        obj = obj[k];
      } else {
        return key;
      }
    }
    return obj;
  }

  subscribe(fn) {
    this.listeners.push(fn);
  }

  applyToDOM() {
    if (typeof document === 'undefined') return;

    // Apply data-i18n attributes
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = this.get(key);
      if (val && typeof val === 'string') {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.placeholder = val;
        } else {
          el.textContent = val;
        }
      }
    });

    // Update Room Selector options
    const roomSelect = document.getElementById('room-selector');
    if (roomSelect) {
      const roomKeys = [
        'main_hall', 'dever_lab', 'library_lounge', 'memory_room',
        'web_room', 'media_hub', 'sports_complex'
      ];
      roomKeys.forEach(r => {
        const opt = document.getElementById(`opt-${r}`);
        if (opt) {
          const count = opt.textContent.match(/\(\d+\)/)?.[0] || '(0)';
          opt.textContent = `${this.get(`rooms.${r}`)} ${count}`;
        }
      });
    }
  }
}

export const i18n = new I18nManager();
